export const MUWEAVE_DICTIONARIES = { zh: { ...zhDict }, en: { ...enDict } }

export type MuweaveTranslator = (key: MuweaveDictKey) => string

export function createFallbackTranslator(lang: 'zh' | 'en' = 'zh'): MuweaveTranslator {
  const table = lang === 'en' ? enDict : zhDict
  return (key) => table[key] ?? zhDict[key]
}

