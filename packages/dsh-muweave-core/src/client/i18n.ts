export function statusTone(status: string | undefined): MuweaveTone {
  if (!status) return 'neutral'
  return STATUS_TONES[status] ?? 'neutral'
}

/** Maps a raw owner enum to a reader label; unknown values pass through unchanged. */
export function statusLabel(status: string | undefined, lang: string): string {
  if (!status) return ''
  const table = lang === 'en' ? STATUS_LABELS.en : STATUS_LABELS.zh
  return table[status] ?? status
}
